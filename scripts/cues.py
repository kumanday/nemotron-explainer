#!/usr/bin/env python3
"""Time scene reveals to narration cues instead of hand-typed seconds.

Put `{@name}` markers in SCRIPT.md where a visual should land and voice it with
`media-tts-frames`; each frame in audio_meta.json then carries `cues[]` with
frame-relative times. Each scene composition names its narration frame with an
empty marker block inside its <script>:

    /* @cues frame=3 */ /* @end-cues */

`python3 scripts/cues.py SLOT` fills every block with the frame's cue times:

    /* @cues frame=3 */ const CUE = {"brief": 0.0, "assets": 4.12}; const SCENE_END = 10.36; /* @end-cues */

so timelines read `tl.from("#chart", {...}, CUE.assets)`. It also writes
SLOT/CUES.md, a cue sheet with the words that follow each cue.

`--check` changes nothing. It fails on stale or missing cue blocks, CUE names
that the frame does not define, narration frames without cues, index.html
scene/voice windows that disagree with audio_meta.json, and timeline positions
written as bare numbers (hand-timed reveals that drift from the voice).
"""
import argparse
from html.parser import HTMLParser
import json
from pathlib import Path
import re
import sys

BLOCK = re.compile(r"/\* @cues frame=(\d+) \*/.*?/\* @end-cues \*/", re.S)
CUE_REF = re.compile(r"CUE\.([A-Za-z_]\w*)|CUE\[\s*['\"]([^'\"]+)['\"]\s*\]")
# A GSAP call whose position argument is a bare positive number: `..., 4.6);`
BARE_POSITION = re.compile(r"(?:\b\w+\.(?:to|from|fromTo|set|add|call)\(.*|^\s*[}\]]\s*),\s*(\d+(?:\.\d+)?)\s*\)\s*;?\s*$")
TOLERANCE = 0.02


class Tags(HTMLParser):
    def __init__(self, source):
        super().__init__()
        self.tags = []
        self.feed(source)

    def handle_starttag(self, tag, attrs):
        self.tags.append((tag, dict(attrs)))


def block_for(voice):
    cues = {cue["name"]: round(cue["t"], 3) for cue in voice.get("cues", [])}
    return (f"/* @cues frame={voice['frame']} */ const CUE = {json.dumps(cues)}; "
            f"const SCENE_END = {round(voice['duration_s'], 3)}; /* @end-cues */")


def scene_files(slot):
    files = sorted((slot / "compositions").glob("*.html")) if (slot / "compositions").is_dir() else []
    return [path for path in files + [slot / "index.html"] if path.is_file()]


def cue_sheet(voices):
    lines = ["# Cue sheet", "", "Generated by scripts/cues.py from audio_meta.json. Times are frame-relative seconds.", ""]
    start = 0.0
    for voice in voices:
        lines.append(f"## Frame {voice['frame']} — starts {start:.2f} s, lasts {voice['duration_s']:.2f} s")
        lines.append("")
        cues = voice.get("cues", [])
        if not cues:
            lines.append("- (no cues)")
        for cue in cues:
            lines.append(f"- `CUE.{cue['name']}` = {cue['t']:.2f} s (film {start + cue['t']:.2f} s): “{cue.get('following', '')}”")
        lines.append("")
        start += voice["duration_s"]
    return "\n".join(lines)


def timing_problems(slot, voices):
    """Compare index.html voice and scene windows with audio_meta.json."""
    problems = []
    index = slot / "index.html"
    if not index.is_file():
        return [f"{index} is missing"]
    tags = Tags(index.read_text()).tags
    by_path = {voice["path"]: voice for voice in voices}
    starts, cumulative = {}, 0.0
    for voice in voices:
        starts[voice["frame"]] = cumulative
        cumulative += voice["duration_s"]
    for tag, attrs in tags:
        if tag == "audio" and attrs.get("src") in by_path:
            voice = by_path[attrs["src"]]
            start, duration = float(attrs.get("data-start", -1)), float(attrs.get("data-duration", -1))
            if abs(start - starts[voice["frame"]]) > TOLERANCE or abs(duration - voice["duration_s"]) > TOLERANCE:
                problems.append(f"{attrs['src']}: data-start {start}/data-duration {duration}, expected "
                                f"{starts[voice['frame']]:.2f}/{voice['duration_s']:.2f}")
        src = attrs.get("data-composition-src")
        if src and (slot / src).is_file():
            match = BLOCK.search((slot / src).read_text())
            if not match:
                continue
            frame = int(match.group(1))
            voice = next((v for v in voices if v["frame"] == frame), None)
            if voice is None:
                problems.append(f"{src}: names frame {frame}, which audio_meta.json does not have")
                continue
            start, duration = float(attrs.get("data-start", -1)), float(attrs.get("data-duration", -1))
            if abs(start - starts[frame]) > TOLERANCE:
                problems.append(f"{src}: host data-start {start}, frame {frame} starts at {starts[frame]:.2f}")
            if duration + TOLERANCE < voice["duration_s"]:
                problems.append(f"{src}: host data-duration {duration} ends before frame {frame} ({voice['duration_s']:.2f} s)")
    return problems


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("slot", type=Path, help="HyperFrames composition directory containing audio_meta.json")
    parser.add_argument("--check", action="store_true", help="report problems without writing")
    args = parser.parse_args()
    slot = args.slot.resolve()
    voices = json.loads((slot / "audio_meta.json").read_text())["voices"]
    by_frame = {voice["frame"]: voice for voice in voices}
    errors, warnings, used_frames = [], [], set()

    for voice in voices:
        count = len(voice.get("cues", []))
        if count == 0:
            errors.append(f"frame {voice['frame']}: no {{@cue}} markers; add them to SCRIPT.md and re-run media-tts-frames")
        elif voice["duration_s"] > 8 and count < 2:
            errors.append(f"frame {voice['frame']}: {voice['duration_s']:.1f} s of narration with one cue; cue each reveal")

    for path in scene_files(slot):
        text = path.read_text()
        name = path.relative_to(slot)
        blocks = list(BLOCK.finditer(text))
        if path.parent.name == "compositions" and not blocks:
            errors.append(f"{name}: no /* @cues frame=N */ /* @end-cues */ block")
        updated = text
        for match in blocks:
            frame = int(match.group(1))
            voice = by_frame.get(frame)
            if voice is None:
                errors.append(f"{name}: frame {frame} is not in audio_meta.json")
                continue
            used_frames.add(frame)
            fresh = block_for(voice)
            if match.group(0) != fresh:
                if args.check:
                    errors.append(f"{name}: cue block for frame {frame} is stale; run scripts/cues.py {args.slot}")
                updated = updated.replace(match.group(0), fresh)
            defined = {cue["name"] for cue in voice.get("cues", [])}
            for ref in CUE_REF.finditer(text):
                cue = ref.group(1) or ref.group(2)
                if cue not in defined:
                    errors.append(f"{name}: CUE.{cue} is not a cue in frame {frame} (has: {', '.join(sorted(defined)) or 'none'})")
        for number, line in enumerate(text.splitlines(), 1):
            bare = BARE_POSITION.search(line)
            if bare and float(bare.group(1)) > 0.75:
                errors.append(f"{name}:{number}: timeline position {bare.group(1)} is hand-timed; use CUE.<name> (+ offset)")
        if not args.check and updated != text:
            path.write_text(updated)
            print(f"updated {name}")

    for frame in by_frame:
        if frame not in used_frames:
            warnings.append(f"frame {frame}: no scene composition reads its cues")
    errors += timing_problems(slot, voices)

    if not args.check:
        (slot / "CUES.md").write_text(cue_sheet(voices) + "\n")
        print(f"wrote {(slot / 'CUES.md').relative_to(slot.parent)}")
    for warning in warnings:
        print(f"warning: {warning}")
    for error in errors:
        print(f"error: {error}")
    if args.check:
        print(json.dumps({"passed": not errors, "errors": len(errors), "warnings": len(warnings)}))
    sys.exit(1 if args.check and errors else 0)


if __name__ == "__main__":
    main()
